const DESIGN_FONTS = {
  display: 'Outfit, ui-sans-serif, system-ui, Helvetica, sans-serif',
  mono: '"JetBrains Mono", ui-monospace, SFMono-Regular, Menlo, monospace',
};

/** Deterministic JSON: keys sorted at every level, two-space indent, trailing newline. */
function stableJson(value) {
  const sortKeys = (node) => {
    if (Array.isArray(node)) return node.map(sortKeys);
    if (node && typeof node === 'object') {
      return Object.fromEntries(
        Object.keys(node)
          .sort()
          .map((key) => [key, sortKeys(node[key])]),
      );
    }
    return node;
  };
  return `${JSON.stringify(sortKeys(value), null, 2)}\n`;
}

function themeCss(palette) {
  const line = (name, value) => `  --color-${name}: ${value};`;
  return [
    '/* Generated by site/scripts/build-data.mjs. Do not edit.',
    '   Colours and type: the maintainer\'s Daylight design, authored in build-data.mjs.',
    `   --color-look-*: the skill's own ${palette.record} record. */`,
    '@theme {',
    ...Object.entries(DESIGN_TOKENS).map(([name, hex]) => line(name, hex)),
    ...Object.entries(palette.colors).map(([name, hex]) => line(`look-${name}`, hex)),
    `  --font-display: ${DESIGN_FONTS.display};`,
    `  --font-mono: ${DESIGN_FONTS.mono};`,
    '}',
    '',
  ].join('\n');
}

function chapterCounts(examples) {
  const counts = Object.fromEntries(CHAPTERS.map((chapter) => [chapter, 0]));
  for (const study of examples) counts[study.chapter] += 1;
  return counts;
}

async function main() {
  const [
    summary,
    sources,
    evidenceEvents,
    evalScale,
    showcase,
    examples,
    palette,
    install,
    studyDirs,
    compatibility,
    catalog,
  ] = await Promise.all([
    readCatalogSummary(),
    readSourceCount(),
    countEvidenceEvents(),
    readEvalScale(),
    readShowcase(),
    readExamples(),
    readPalette(),
    readInstall(),
    countStudyDirectories(),
    readCompatibility(),
    readCatalog(),
  ]);

  if (examples.length !== studyDirs) {
    throw new Error(
      `build-data: examples/README.md lists ${examples.length} studies but examples/ ships ${studyDirs} runnable directories`,
    );
  }

  const stats = {
    recipes: summary.recipes,
    knowledge: summary.knowledge,
    blueprints: summary.blueprints,
    directions: summary.directions,
    sources,
    evidence_events: evidenceEvents,
    studies: examples.length,
    showcase_frames: showcase.length,
    eval_scale: evalScale,
  };

  await mkdir(outDir, { recursive: true });
  const files = {
    'stats.json': stableJson(stats),
    'examples.json': stableJson(examples),
    'catalog.json': stableJson(catalog),
    'showcase.json': stableJson(showcase),
    'palette.json': stableJson(palette),
    'install.json': stableJson(install),
    'compatibility.json': stableJson(compatibility),
    'theme.css': themeCss(palette),
  };
  for (const [name, contents] of Object.entries(files)) {
    await writeFile(new URL(name, outDir), contents);
  }

  const counts = chapterCounts(examples);
  const clips = examples.filter((study) => study.clip !== null).length;
  console.log(
    `build-data: ${stats.studies} studies (${CHAPTERS.map((c) => counts[c]).join(' / ')}), ` +
      `${clips} hover clips on disk, ${stats.showcase_frames} frames, ` +
      `${stats.evidence_events} evidence events, ${Object.keys(palette.colors).length} look tokens, ` +
      `${install.length} install tabs, ${compatibility.length} compatibility rows, ` +
      `catalog groups ${catalog.directions.length} directions / ${catalog.kinds.length} knowledge kinds / ` +
      `${catalog.blueprints.length} blueprints.`,
  );
}

await main();
